import assert from 'node:assert/strict';
import vm from 'node:vm';
import { readFileSync } from 'node:fs';
const code = readFileSync(new URL('./background.js', import.meta.url), 'utf8');
let state = { pinLockEnabled:true, pinVerify:{}, pinFailCount:4, vaultBlob:{ct:'preserve'} };
const context = vm.createContext({ chrome:{storage:{local:{ get:async()=>({...state}),set:async patch=>Object.assign(state,patch)}}}, MAX_FAIL:5, UNLOCK_MS_DEFAULT:600000, verifyPinHash:async()=>false, clearMemSession(){}, markUnlocked:async()=>{}, Date });
vm.runInContext(code.slice(code.indexOf('async function pinAttemptBlocked('), code.indexOf('async function handleVaultSave(')),context);
const result = await context.handlePinUnlock({pin:'0000'});
assert.equal(result.ok,false);
assert.equal(state.pinLockEnabled,true);
assert.equal(state.vaultBlob.ct,'preserve');
assert.ok(state.pinBlockedUntil>Date.now());
assert.equal((await context.handlePinUnlock({pin:'0000'})).ok,false);
let updates = [];
let dock = { left: 906, top: 80, width: 280, height: 560, focused: false };
const position = vm.createContext({ loadGlobalDock: async()=>{}, saveGlobalDock:async()=>{}, GLOBAL_DOCK:{dockWinId:1}, DOCK_W:280, getDockTarget:async()=>({windowId:2,title:'업무'}), chrome:{windows:{get:async id=>id===1?dock:{left:0,top:80,width:900,height:560},update:async(id,patch)=>updates.push(patch)}} });
vm.runInContext(code.slice(code.indexOf('async function repositionGlobalDock('),code.indexOf('async function ensureGlobalDock(')),position);
await position.repositionGlobalDock();
assert.equal(updates.length,0);
dock.left=0;
await position.repositionGlobalDock();
assert.equal(updates.length,1);
assert.equal('focused' in updates[0],false);
dock.width=640; dock.height=900;
await position.repositionGlobalDock();
assert.equal(updates.at(-1).width,640);
assert.equal(updates.at(-1).height,900);
const beforeFocus=updates.length;
dock.focused=true;
await position.repositionGlobalDock();
assert.equal(updates.length,beforeFocus);
assert.equal(code.includes('raisePinnedDock'),false);
console.log('PASS: PIN cooldown; unchanged bounds skipped; reposition preserves focus; active dock not moved; focus bounce removed');
