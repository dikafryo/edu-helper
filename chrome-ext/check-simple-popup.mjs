import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFileSync} from 'node:fs';
const html=readFileSync(new URL('./popup.html',import.meta.url),'utf8');
assert.deepEqual([...html.matchAll(/data-action="([^"]+)"/g)].map(m=>m[1]),['settings','portal','neis','edufine','daily','trip']);
assert.ok(!html.includes('role="tablist"'));assert.ok(html.includes('교직원 업무도우미'));
const handlers={},status={},calls=[];let settingsOpened=0,closed=0;const dockButton={disabled:false,addEventListener:(name,fn)=>handlers.dock=fn};
const mailButton={disabled:false,addEventListener:(name,fn)=>handlers.mail=fn};
const buttons=['settings','portal','neis','edufine','daily','trip'].map(action=>({dataset:{action},disabled:false}));
const context=vm.createContext({window:{close:()=>closed++},document:{getElementById:id=>id==='btnOpenDock'?dockButton:id==='btnOfficialMail'?mailButton:status,querySelector:()=>({addEventListener:(name,fn)=>handlers[name]=fn}),querySelectorAll:()=>buttons},chrome:{runtime:{openOptionsPage:async()=>{settingsOpened++;},sendMessage:async m=>{calls.push(m);return {ok:true,message:'열림'};}}}});
vm.runInContext(readFileSync(new URL('./popup.js',import.meta.url),'utf8').replace(/^import[^\n]+\n/,''),context);
for(const button of buttons)await handlers.click({target:{closest:()=>button}});
assert.equal(settingsOpened,1);
assert.deepEqual(calls.map(m=>m.type),['QUICK_OPEN','QUICK_OPEN','QUICK_OPEN','OPEN_WORK_PAGE','OPEN_WORK_PAGE']);
assert.deepEqual(calls.map(m=>m.target||m.page),['portal','neis','edufine','daily','trip']);
assert.ok(buttons.every(b=>!b.disabled));
await handlers.dock();assert.equal(calls.at(-1).type,'OPEN_DOCK');assert.equal(closed,1);
await handlers.mail();assert.equal(calls.at(-1).type,'OFFICIAL_MAIL_OPEN');assert.equal(mailButton.disabled,false);
console.log('PASS (mock): six popup actions, settings page, correct portal/work-page routes and button recovery');
