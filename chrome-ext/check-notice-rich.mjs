import assert from 'node:assert/strict';
import { noticeWithTables, copyNotice } from './lib/notice-rich.js';
const tables = [[[{text:'일시',rowSpan:2},{text:'2026. 11. 2.'}],[{text:'<script>악성</script>'}]],[[{text:'장소',colSpan:2}]]];
const result = noticeWithTables('행사', '1. 행사 참석을 안내합니다.', tables);
assert.equal(result.count,2);
assert.equal((result.html.match(/<table /g)||[]).length,2);
assert.ok(result.html.includes('rowspan="2"'));
assert.ok(result.html.includes('colspan="2"'));
assert.ok(!result.html.includes('<script>'));
assert.ok(result.html.indexOf('<table')<result.html.indexOf('나. 기간'));
assert.ok(result.text.includes('2026. 11. 2.'));
assert.equal(noticeWithTables('제목','본문').count,0);
assert.throws(()=>noticeWithTables('','',Array(21).fill([])));
let written;
Object.defineProperty(globalThis,'navigator',{value:{clipboard:{write:async items=>{written=items;}}}, configurable:true});
globalThis.ClipboardItem=class { constructor(data){this.data=data;} };
await copyNotice(result.html,result.text);
assert.ok(written[0].data['text/html']);
assert.ok(written[0].data['text/plain']);
assert.ok((await written[0].data['text/html'].text()).includes('<!--StartFragment-->'));
console.log('PASS: notice conversion with two tables, merged cells, escaping, placement, text fallback and dual-format clipboard call (mock)');
